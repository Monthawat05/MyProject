import '../models/trip_model.dart';

class FeaturedTrip {
  final TripModel trip;
  final String imageQuery;
  final String tagline;
  FeaturedTrip.fromMap(Map<String, dynamic> data)
    : imageQuery = data['imageQuery'] as String,
      tagline = data['tagline'] as String,
      trip = TripModel(
        userId: '',
        destination: data['destination'] as String,
        days: data['days'] as int,
        travelers: data['travelers'] as int,
        budget: 'ไม่ระบุ',
        styles: List<String>.from(data['styles'] as List),
        itinerary: data['itinerary'] as String,
        createdAt: DateTime(2026),
      );
  FeaturedTrip(
    String destination,
    this.imageQuery,
    this.tagline,
    List<String> styles,
    List<String> dayPlans,
  ) : trip = TripModel(
        destination: destination,
        userId: '',
        days: dayPlans.length,
        travelers: 2,
        budget: 'ไม่ระบุ',
        styles: styles,
        createdAt: DateTime(2026),
        itinerary:
            '## แผนตัวอย่าง: $destination\n\n'
            'ทริปแนะนำสำหรับใช้เป็นไอเดีย ไม่ใช่อันดับจากยอดเข้าชมหรือคะแนนรีวิว\n\n'
            '${dayPlans.asMap().entries.map((e) => '## Day ${e.key + 1}\n${e.value}').join('\n\n')}\n\n'
            '### ก่อนออกเดินทาง\nตรวจสอบเวลาเปิด สภาพอากาศ การเดินทาง และราคาที่พักกับผู้ให้บริการอีกครั้ง สามารถสร้างแผนด้วย AI เพื่อปรับให้ตรงกับต้นทาง วันเดินทาง และงบของคุณได้',
      );
}

